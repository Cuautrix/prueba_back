CREATE TABLE cat_entidad_federativa
(
    id_entidad_federativa BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_by            VARCHAR(255)                            NOT NULL,
    updated_by            VARCHAR(255),
    created_at            TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at            TIMESTAMP WITHOUT TIME ZONE,
    trace                 INTEGER,
    active                BOOLEAN,
    descripcion           VARCHAR(255),
    codigo_estado         VARCHAR(255),
    codigo_num_estado     BIGINT,
    CONSTRAINT pk_cat_entidad_federativa PRIMARY KEY (id_entidad_federativa)
);